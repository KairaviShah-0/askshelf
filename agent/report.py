"""Self-contained HTML executive report (charts included) that a manager can download, email or print to PDF."""
from __future__ import annotations

import html

import pandas as pd

from . import tools as T
from . import tools_pro as PRO

_CSS = """
body{font-family:Inter,system-ui,-apple-system,'Segoe UI',sans-serif;color:#0b0b0b;background:#f6f5f1;margin:0}
.wrap{max-width:1040px;margin:0 auto;padding:32px 24px 64px}
.hero{background:linear-gradient(120deg,#0f1b2d,#1c3f73 60%,#2a78d6);color:#fff;border-radius:18px;padding:28px 32px;margin-bottom:24px}
.hero h1{margin:0 0 6px;font-size:28px}.hero p{margin:0;color:#cfe0f7}
.score{display:flex;gap:16px;align-items:center;margin:0 0 20px}.big{font-size:56px;font-weight:700;line-height:1}
.card{background:#fff;border:1px solid #e6e4dc;border-radius:14px;padding:18px 20px;margin-bottom:18px}
h2{font-size:18px;margin:0 0 10px}.insight{border-left:4px solid #2a78d6;background:#f4f8fe;padding:8px 12px;border-radius:0 10px 10px 0;margin:6px 0}
.action{border-left:4px solid #1baf7a;background:#f1faf6;padding:8px 12px;border-radius:0 10px 10px 0;margin:6px 0}
table{border-collapse:collapse;width:100%;font-size:13px}th,td{border-bottom:1px solid #eceae3;padding:6px 8px;text-align:left}th{color:#6b6a65;font-weight:600}
.foot{color:#898781;font-size:12px;margin-top:28px}
@media print{body{background:#fff}.card{break-inside:avoid}}
"""


def _table(df: pd.DataFrame | None) -> str:
    return "" if df is None or df.empty else df.to_html(index=False, border=0, escape=True)


def build_html(period: str = "last_quarter") -> str:
    res = PRO.executive_briefing(period)
    hs = PRO.health_score(period)
    fig_blocks, first = [], True
    charts = [("Profit bridge", res.chart)] + list(res.extra_charts)
    for label, fig in charts:
        if fig is None:
            continue
        fig_blocks.append(f"<div class='card'><h2>{html.escape(label)}</h2>"
                          + fig.to_html(full_html=False, include_plotlyjs="cdn" if first else False, config={"displayModeBar": False}) + "</div>")
        first = False
    comp = "".join(f"<tr><td>{html.escape(k)}</td><td>{v:.0f} / 100</td></tr>" for k, v in hs["components"].items())
    ins = "".join(f"<div class='insight'>{html.escape(i)}</div>" for i in res.insights)
    act = "".join(f"<div class='action'>{html.escape(a)}</div>" for a in res.actions)
    facts = "".join(f"<li>{html.escape(f)}</li>" for f in res.facts)
    tables = "".join(f"<div class='card'><h2>{html.escape(c)}</h2>{_table(t)}</div>" for c, t in res.extra_tables if c != "Revenue outlook")
    return f"""<!doctype html><html><head><meta charset='utf-8'><title>AskShelf Executive Briefing</title><style>{_CSS}</style></head>
<body><div class='wrap'>
<div class='hero'><h1>Executive briefing</h1><p>AskShelf for Modern Furniture Co. | {html.escape(res.period)}</p></div>
<div class='card'><div class='score'><div class='big'>{hs['score']:.0f}</div><div><b>Business health: {hs['label']}</b><br><span style='color:#6b6a65'>out of 100, from five weighted components</span></div></div>
<table><tr><th>Component</th><th>Score</th></tr>{comp}</table></div>
<div class='card'><h2>Headlines</h2><ul>{facts}</ul></div>
<div class='card'><h2>What stands out</h2>{ins}</div>
<div class='card'><h2>Recommended actions</h2>{act}</div>
<div class='card'><h2>Scorecard</h2>{_table(res.table)}</div>
{''.join(fig_blocks)}{tables}
<p class='foot'>Generated by AskShelf, the Retail Sales Intelligence Assistant. Only aggregated figures are shown; customer and employee identifiers are never included.
Forecasts and risk scores are statistical estimates - see the method notes in the app.</p>
</div></body></html>"""
