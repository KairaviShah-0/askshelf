"""Excel exports: a full report workbook (summary, one sheet per analysis, forecast, profile, queries) and single-result exports."""
from __future__ import annotations

import io

import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

from .labreport import Report

NAVY = "1F3864"
HEAD_FONT = Font(bold=True, color="FFFFFF", name="Calibri", size=10)
HEAD_FILL = PatternFill("solid", fgColor=NAVY)
THIN = Side(style="thin", color="D5DBE5")


def _sheet_name(n: str, used: set) -> str:
    base = "".join(c for c in n if c not in "[]:*?/\\")[:28] or "Sheet"
    k, i = base, 2
    while k in used:
        k, i = f"{base[:25]}_{i}", i + 1
    used.add(k)
    return k


def _write_df(ws, df: pd.DataFrame, start_row: int = 1) -> int:
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_datetime64_any_dtype(d[c]):
            d[c] = d[c].dt.strftime("%Y-%m-%d")
    for j, c in enumerate(d.columns, 1):
        cell = ws.cell(row=start_row, column=j, value=str(c))
        cell.font, cell.fill = HEAD_FONT, HEAD_FILL
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    for i, row in enumerate(d.itertuples(index=False), start_row + 1):
        for j, v in enumerate(row, 1):
            if isinstance(v, float) and pd.isna(v):
                v = None
            cell = ws.cell(row=i, column=j, value=v)
            cell.border = Border(bottom=THIN)
            if isinstance(v, float):
                cell.number_format = "#,##0.00"
            elif isinstance(v, int) and not isinstance(v, bool):
                cell.number_format = "#,##0"
    for j, c in enumerate(d.columns, 1):
        width = max([len(str(c))] + [len(str(x)) for x in d[c].head(200)]) + 2
        ws.column_dimensions[get_column_letter(j)].width = min(max(width, 10), 48)
    ws.freeze_panes = ws.cell(row=start_row + 1, column=1)
    if len(d):
        ws.auto_filter.ref = f"A{start_row}:{get_column_letter(len(d.columns))}{start_row + len(d)}"
    return start_row + len(d)


def table_xlsx(df: pd.DataFrame, title: str = "Result", sql: str | None = None, question: str | None = None) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Result"
    _write_df(ws, df)
    info = wb.create_sheet("About")
    info["A1"], info["A1"].font = title, Font(bold=True, size=14, color=NAVY)
    rows = [("Question", question or ""), ("Query", sql or "(forecast)"), ("Rows", len(df)), ("Generated by", "AskShelf Data Lab")]
    for i, (k, v) in enumerate(rows, 3):
        info.cell(row=i, column=1, value=k).font = Font(bold=True)
        info.cell(row=i, column=2, value=v).alignment = Alignment(wrap_text=True, vertical="top")
    info.column_dimensions["A"].width, info.column_dimensions["B"].width = 16, 100
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def report_xlsx(rep: Report) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    ws["A1"], ws["A1"].font = rep.title, Font(bold=True, size=16, color=NAVY)
    ws["A2"] = f"{rep.subtitle} | {rep.date} | Prepared by {rep.prepared_by}" + (f" for {rep.prepared_for}" if rep.prepared_for else "")
    ws["A2"].font = Font(italic=True, color="6B7280")
    r = 4
    ws.cell(row=r, column=1, value="Executive summary").font = Font(bold=True, color=NAVY, size=12)
    for p in rep.exec_summary:
        r += 1
        c = ws.cell(row=r, column=1, value=p)
        c.alignment = Alignment(wrap_text=True, vertical="top")
        ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=4)
        ws.row_dimensions[r].height = 15 * max(2, len(p) // 95 + 1)
    r += 2
    ws.cell(row=r, column=1, value="Key findings").font = Font(bold=True, color=NAVY, size=12)
    r = _write_df(ws, pd.DataFrame([{"Section": f"{i + 3}. {s.title}", "Key finding": s.key_finding, "Sheet": ""} for i, s in enumerate(rep.sections)]).drop(columns="Sheet"), r + 1)
    r += 2
    ws.cell(row=r, column=1, value="Recommendations").font = Font(bold=True, color=NAVY, size=12)
    r = _write_df(ws, pd.DataFrame([{"Priority": f"R{i}", "Action": x["title"], "Rationale": x["detail"]} for i, x in enumerate(rep.recommendations, 1)]), r + 1)
    ws.freeze_panes = None
    ws.auto_filter.ref = None
    ws.column_dimensions["A"].width, ws.column_dimensions["B"].width, ws.column_dimensions["C"].width, ws.column_dimensions["D"].width = 42, 70, 60, 10
    used = {"Summary"}
    for i, s in enumerate(rep.sections, 3):
        if s.full_df is not None and len(s.full_df):
            wsx = wb.create_sheet(_sheet_name(f"{i}. {s.title}", used))
            _write_df(wsx, s.full_df.head(5000))
    if rep.data_dict is not None:
        _write_df(wb.create_sheet(_sheet_name("Data dictionary", used)), rep.data_dict)
    q = wb.create_sheet(_sheet_name("Queries", used))
    _write_df(q, pd.DataFrame([{"Section": f"{i + 3}. {s.title}", "SQL": s.sql or "Prophet forecast (no SQL)"} for i, s in enumerate(rep.sections)]))
    q.column_dimensions["B"].width = 120
    for row in q.iter_rows(min_row=2):
        row[1].alignment = Alignment(wrap_text=True, vertical="top")
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
